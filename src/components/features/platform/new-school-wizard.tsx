"use client";

import { zodResolver } from "@hookform/resolvers/zod";
import { ArrowLeft, ArrowRight } from "lucide-react";
import { useLocale, useTranslations } from "next-intl";
import { useState, useTransition } from "react";
import { useForm } from "react-hook-form";
import { toast } from "sonner";

import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { addDays, todayInCasablanca } from "@/lib/dates";
import { generateTemporaryPassword } from "@/lib/password";
import { createSchool } from "@/lib/platform/actions";
import type { PlanOption } from "@/lib/platform/plans";
import {
  newSchoolSchema,
  WIZARD_STEPS,
  type NewSchoolFormValues,
  type NewSchoolInput,
} from "@/lib/validations/platform";

import { WizardDirectorStep } from "./wizard-director-step";
import { WizardPlanStep } from "./wizard-plan-step";
import { WizardSchoolStep } from "./wizard-school-step";
import { WizardStepper } from "./wizard-stepper";
import { WizardSuccess } from "./wizard-success";

const TRIAL_DAYS = 30;

type Seed = { password: string; today: string };

function defaultValues(locale: string, plans: PlanOption[], { password, today }: Seed): NewSchoolFormValues {
  return {
    name: "",
    slug: "",
    city: "",
    phone: "",
    address: "",
    directorName: "",
    directorEmail: "",
    directorLocale: locale as NewSchoolFormValues["directorLocale"],
    directorPassword: password,
    planId: plans[0]?.id ?? "",
    subscriptionStatus: "trial",
    startDate: today,
    trialEndsOn: addDays(today, TRIAL_DAYS),
    endDate: "",
  };
}

type Created = { schoolName: string; email: string; password: string };

type Props = {
  plans: PlanOption[];
  /** Generated by the page on the server, so SSR and hydration agree. */
  initialPassword: string;
  today: string;
};

export function NewSchoolWizard({ plans, initialPassword, today }: Props) {
  const t = useTranslations("platform.wizard");
  const tErrors = useTranslations("platform.errors");
  const locale = useLocale();
  const [step, setStep] = useState(0);
  const [slugEdited, setSlugEdited] = useState(false);
  const [created, setCreated] = useState<Created | null>(null);
  const [isPending, startTransition] = useTransition();

  const form = useForm<NewSchoolFormValues, unknown, NewSchoolInput>({
    resolver: zodResolver(newSchoolSchema),
    defaultValues: defaultValues(locale, plans, { password: initialPassword, today }),
  });

  const isLast = step === WIZARD_STEPS.length - 1;

  async function goNext() {
    const valid = await form.trigger([...WIZARD_STEPS[step]!.fields]);
    if (valid) setStep((s) => s + 1);
  }

  function submit() {
    // Raw (untransformed) values: the Server Action validates them again.
    const values = form.getValues();
    startTransition(async () => {
      const result = await createSchool(values);
      if (!result.ok) {
        const { field, error } = result;
        if (field) {
          form.setError(field, { message: error });
          // Back to the step that holds the faulty field.
          const target = WIZARD_STEPS.findIndex((s) => (s.fields as readonly string[]).includes(field));
          if (target >= 0) setStep(target);
        }
        toast.error(tErrors(error));
        return;
      }
      toast.success(t("success.toast", { name: values.name }));
      setCreated({
        schoolName: values.name.trim(),
        email: values.directorEmail.trim().toLowerCase(),
        password: values.directorPassword,
      });
    });
  }

  function reset() {
    form.reset(
      defaultValues(locale, plans, { password: generateTemporaryPassword(), today: todayInCasablanca() }),
    );
    setSlugEdited(false);
    setCreated(null);
    setStep(0);
  }

  if (created) {
    return (
      <Card>
        <CardContent>
          <WizardSuccess {...created} onCreateAnother={reset} />
        </CardContent>
      </Card>
    );
  }

  const stepKey = WIZARD_STEPS[step]!.key;

  return (
    <Card>
      <CardHeader className="gap-4">
        <WizardStepper current={step} />
        <CardTitle>{t(`steps.${stepKey}`)}</CardTitle>
      </CardHeader>
      <CardContent>
        <form
          noValidate
          onSubmit={(e) => {
            e.preventDefault();
            // Enter on an early step = "Next"; only the last step creates the school.
            if (isLast) void form.handleSubmit(submit)();
            else void goNext();
          }}
          className="flex flex-col gap-6"
        >
          {step === 0 && (
            <WizardSchoolStep form={form} slugEdited={slugEdited} onSlugEdited={() => setSlugEdited(true)} />
          )}
          {step === 1 && <WizardDirectorStep form={form} />}
          {step === 2 && <WizardPlanStep form={form} plans={plans} />}

          <div className="flex justify-between gap-2">
            <Button
              type="button"
              variant="outline"
              onClick={() => setStep((s) => s - 1)}
              disabled={step === 0 || isPending}
            >
              <ArrowLeft className="rtl:-scale-x-100" aria-hidden />
              {t("back")}
            </Button>
            <Button type="submit" disabled={isPending}>
              {isLast ? (isPending ? t("creating") : t("create")) : t("next")}
              {!isLast && <ArrowRight className="rtl:-scale-x-100" aria-hidden />}
            </Button>
          </div>
        </form>
      </CardContent>
    </Card>
  );
}
